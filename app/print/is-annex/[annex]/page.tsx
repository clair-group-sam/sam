import { notFound, redirect } from "next/navigation";
import { getSession } from "@/lib/session";
import { supabaseAdmin } from "@/lib/supabase-admin";
import PrintAuto from "@/components/PrintAuto";
import { ANNEXES, SECTORS, annexData } from "@/lib/is-annex";

export const dynamic = "force-dynamic";
const CSS = `
@page { size: A4 landscape; margin: 12mm 10mm; @bottom-right { content: "Page " counter(page) " / " counter(pages); font: 9px Inter, Arial; color: #6b7a8c } }
body{background:#fff}
.mn{font:10px/1.4 Inter, Arial, sans-serif;color:#0d2a3f}
.mn h1{font-size:17px;margin:0 0 2px}.mn h2{font-size:12px;margin:14px 0 4px;padding-bottom:3px;border-bottom:1.5px solid #0d2a3f}
.mn table{width:100%;border-collapse:collapse;margin:4px 0}.mn th,.mn td{border:1px solid #c9d3dc;padding:3px 5px;vertical-align:top;text-align:left}.mn th{background:#f1f5f8}
.mn .mini{font-size:8.5px;color:#6b7a8c}.mn .c{color:#b42318;font-weight:700}.mn .s{color:#b54708;font-weight:700}.mn .w{color:#475467}
.mn tr{break-inside:avoid}
`;
const LV: Record<string, [string, string]> = { critical: ["c", "Critical"], serious: ["s", "To address"], warning: ["w", "To monitor"] };
const CT: Record<string, string> = { ok: "Confirmed", tbc: "To confirm", none: "None" };
const ENTN: Record<string, string> = { ASJMT: "ASJMT", ASJFR: "ASJFR", ASFFR: "ASFFR" };

/** PRO-IS-01 annex, printed from the Part-IS registers: the list of systems and interfaces of IS.I.OR.205(a)/(b), always current. */
export default async function IsAnnex({ params, searchParams }: { params: Promise<{ annex: string }>; searchParams: Promise<{ auto?: string }> }) {
  const { annex } = await params; const sp = await searchParams;
  const s = await getSession(); if (!s) redirect("/login");
  if (!ANNEXES[annex]) notFound();
  const db = supabaseAdmin();
  const { A, systems, awaiting, flows } = await annexData(db, annex);
  const printed = new Date().toLocaleString("en-GB", { timeZone: "UTC", dateStyle: "medium", timeStyle: "short" }) + " UTC";
  await db.from("audit_log").insert({ actor: s.person?.id ?? null, entity: A.ents[0], object_type: "is_annex", object_id: annex, action: "printed", after: { systems: systems.length } });
  return (
    <div className="mn" style={{ maxWidth: 1100, margin: "0 auto", padding: 20 }}>
      <style>{CSS}</style>
      <PrintAuto fileName={`${A.title.split(",")[0]} annex ${new Date().toISOString().slice(0, 10)}`} auto={sp.auto === "1"} />
      <div className="mini">Generated by S.A.M. from the Part-IS registers on {printed} by {s.name}. A printed copy is valid on that date only.</div>
      <h1>{A.title}</h1>
      <div>Information systems and interfaces relevant to aviation safety (IS.I.OR.205(a)/(b), AMC1 IS.I.OR.205(b)). {A.basis}</div>
      <p className="mini">{systems.length} systems, {systems.filter((x) => x.level === "critical").length} critical, {systems.filter((x) => x.contractState === "tbc" && x.resp !== "auth").length} contracts or Part-IS clauses to confirm, {awaiting.length} department(s) without reply. Attention level: from the IS risk assessment when one exists (highest live score), otherwise the level set in the register.</p>
      {SECTORS.map(([k, t, sub]) => { const list = systems.filter((x) => (x.resp ?? "own") === k); if (!list.length) return null; return (
        <section key={k}>
          <h2>{t} ({list.length})</h2><div className="mini">{sub}</div>
          <table><thead><tr><th style={{ width: "15%" }}>System</th><th style={{ width: "11%" }}>Department</th><th>Purpose, data</th><th style={{ width: "13%" }}>Hosting, provider</th><th style={{ width: 40 }}>Ops</th><th style={{ width: "17%" }}>Contract</th><th style={{ width: "15%" }}>Attention, IS risks</th>{A.ents.length > 1 && <th style={{ width: 60 }}>Entity</th>}</tr></thead>
            <tbody>{list.map((x) => <tr key={x.id}>
              <td><b>{x.name}</b><div className="mini">{x.short}</div></td><td>{x.dept}</td>
              <td>{x.purpose}<div className="mini">{x.data}</div></td><td>{x.hosting}<div className="mini">{x.provider}</div></td>
              <td>{x.ops_impact === "Y" ? "Yes" : x.ops_impact === "N" ? "No" : "?"}</td>
              <td>{CT[x.contractState ?? ""] ?? ""}{x.contractTxt && <div className="mini">{x.contractTxt}</div>}</td>
              <td>{x.level ? <span className={LV[x.level][0]}>{LV[x.level][1]}</span> : ""}{x.risks.length ? <div className="mini">{x.risks.map((r) => `${r.score || "?"}: ${r.threat} (${r.status})`).join("; ")}</div> : <div className="mini">no IS risk assessment</div>}</td>
              {A.ents.length > 1 && <td>{x.ents.map((e) => ENTN[e] ?? e).join(", ")}</td>}
            </tr>)}</tbody></table>
        </section>); })}
      <h2>Interfaces</h2>
      {flows.length ? <table><thead><tr><th>From</th><th>To</th><th>Data</th><th>Means</th><th>Contract</th><th>Part-IS clause</th><th>Criticality</th></tr></thead><tbody>
        {flows.map((f, i) => <tr key={i}><td>{f.from_system}</td><td>{f.to_system}</td><td>{f.data ?? ""}</td><td>{f.means ?? ""}</td><td>{f.contract_ref ?? ""}</td><td>{f.is_clause === true ? "Yes" : f.is_clause === false ? "No" : "Not recorded"}</td><td>{f.criticality}</td></tr>)}
      </tbody></table> : <p className="mini">No interface recorded.</p>}
      {awaiting.length > 0 && <><h2>Departments without reply</h2><p>{awaiting.map((x) => x.name).join("; ")}. Inventory e-mail of 31/03/2026; their systems are not listed yet.</p></>}
      <h2>Cross-cutting finding</h2>
      <p>Almost all systems are cloud based, with no local redundancy and no contracted 24/7 IT support (written alert, 31/03/2026): addressed under IS.I.OR.220 (detection, response, recovery) and IS.I.OR.235 (contracting). The ERP binder printed from S.A.M. is the fallback when the systems are down. OEM portal addresses are kept in the internal register, not in this annex.</p>
    </div>
  );
}
