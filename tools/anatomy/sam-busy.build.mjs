// a turbofan, a propeller nose and a flat-four piston engine, each on a small test stand, with one part that turns.
import { writeFileSync } from "node:fs";
import * as k from "../../anatomy-kit/kit/iso-kit.mjs";
import * as G from "../../anatomy-kit/kit/lathe.mjs";

const SIZE = 64;
const S = (p, o) => k.solidSvg(p, o);
const L = (d, o) => k.lineSvg(d, o);
const r1 = (n) => Math.round(n * 100) / 100;

function stand(P, { plate, posts, top }) {
  const out = [S(k.slabOf(plate, -3, 3, P, 3, 0.5), { tone: "mid" })];
  for (const p of posts) out.push(S(k.slabOf(p, 0, top, P, 2), { tone: "mid" }));
  return out.join("");
}
/** The turning group: blades drawn in the plane x = const (local u = world y, local v = world z), projected by one matrix. */
function spinOf(P, centre, markup, cls) {
  const [a, b] = k.axisVector(P, [0, 1, 0]); const [c, d] = k.axisVector(P, [0, 0, 1]); const [e, f] = k.iso(centre, P);
  return `<g transform="matrix(${[a, b, c, d, e, f].map(r1).join(" ")})"><g class="sb-spin ${cls}">${markup}</g></g>`;
}
const rot = (n, d, extra = "") => Array.from({ length: n }, (_, i) => `<path transform="rotate(${r1((360 / n) * i)})" d="${d}" ${extra}/>`).join("");

function fan() {
  const Z = 21, R = 11;
  const pts = [[-26, -R, Z - R], [-26, R, Z + R], [1, -R, Z - R], [1, R, Z + R], [1, R, Z - R], [1, -R, Z + R], ...k.boxCorners({ x: -24, y: -9, w: 24, d: 18, r: 2 }, -3, 0), [5, 0, Z]];
  const P = k.fitProjection(pts, SIZE, SIZE, { pad: 3 });
  const F = G.frameAlong([0, 0, Z], [1, 0, 0]);
  const body = G.solidOf([[-26, 5.2], [-21, 7.4, 1], [-12, 10.4, 1], [-3, 11, 1], [0, 10]], F, P);
  const intake = G.circleOf(F, 0, 8.7, P);
  const blades = rot(11, "M0 -2.9Q3.4 -5.4 1.6 -8.3", 'class="iso-line" data-tone="mid"');
  const hub = G.sphereOf([1.2, 0, Z], 2.9, P);
  return { P, body: [
    stand(P, { plate: { x: -24, y: -9, w: 24, d: 18, r: 2 }, posts: [{ x: -15, y: -2.5, w: 7, d: 5, r: 1 }], top: Z - 9 }),
    S(body, { tone: "hi" }),
    `<path class="sb-bore" d="${intake}"/>`, L(intake, { tone: "hi" }),
    spinOf(P, [0, 0, Z], blades, "fast"),
    S(hub, { tone: "hi", lit: true }),
    spinOf(P, [3.6, 0, Z], `<circle class="sb-dot" cx="0.9" cy="-0.9" r="0.55"/>`, "fast"),
  ].join("") };
}

function prop() {
  const Z = 21, R = 8.5, B = 16;
  const pts = [[-22, -R, Z - R], [-22, R, Z + R], [0, -R, Z + R], [0, R, Z + R], [-22, -R, Z + R], [2, -B, Z], [2, B, Z], [2, 0, Z + B], [2, 0, Z - B], [9, 0, Z], ...k.boxCorners({ x: -22, y: -8, w: 20, d: 16, r: 2 }, -3, 0)];
  const P = k.fitProjection(pts, SIZE, SIZE, { pad: 3 });
  const F = G.frameAlong([0, 0, Z], [1, 0, 0]);
  const cowl = G.solidOf([[-22, 8.5], [-7, 8.5, 1], [-2, 6.6, 1], [0, 4.2]], F, P);
  const blade = "M0 -2C-2.6 -5.5 -2.9 -11.5 -0.3 -15.8C2.3 -12 2.1 -5.5 0 -2Z";
  const blades = rot(3, blade, 'class="sb-blade"');
  const spinner = G.solidOf([[1, 3.3], [4.2, 2.5, 1], [7.4, 0.5, 1]], F, P);
  return { P, body: [
    stand(P, { plate: { x: -22, y: -8, w: 20, d: 16, r: 2 }, posts: [{ x: -15, y: -2.5, w: 7, d: 5, r: 1 }], top: Z - 7 }),
    S(cowl, { tone: "hi" }),
    L(G.arcOf(F, -7, 8.5, P), { tone: "faint" }),
    spinOf(P, [2, 0, Z], blades, ""),
    S(spinner, { tone: "hi", lit: true }),
  ].join("") };
}

function piston() {
  const Z = 17, B = 13;
  const plate = { x: -20, y: -11, w: 30, d: 22, r: 2 };
  const pts = [...k.boxCorners(plate, -3, 0), [-16, -15, Z], [-16, 15, Z + 4], [8, 15, Z], [14, -B, Z], [14, B, Z], [14, 0, Z + B], [14, 0, Z - B], [17, 0, Z]];
  const P = k.fitProjection(pts, SIZE, SIZE, { pad: 3 });
  const out = [stand(P, { plate, posts: [{ x: -14, y: -3, w: 5, d: 6, r: 1 }, { x: 1, y: -3, w: 5, d: 6, r: 1 }], top: Z - 5 })];
  const cyl = (cx, side) => {
    const F = G.frameAlong([cx, side * 5, Z], [0, side, 0]);
    const fins = [2.4, 4.4, 6.4].map((s) => G.arcOf(F, s, 4.1, P)).join("");
    return S(G.disc(0, 8.2, 4.1, F, P), { tone: "hi", inner: L(fins, { tone: "lo" }) }) + S(G.disc(8.2, 9.8, 3, F, P), { tone: "mid" });
  };
  out.push(cyl(-9, -1), cyl(1, -1));
  out.push(S(k.slabOf({ x: -17, y: -5, w: 25, d: 10, r: 2.4 }, Z - 5, 10, P, 4, 0.5), { tone: "hi" }));
  out.push(cyl(-9, 1), cyl(1, 1));
  const FX = G.frameAlong([8, 0, Z], [1, 0, 0]);
  out.push(S(G.disc(0, 5, 2.4, FX, P), { tone: "mid" }));
  const blade = "M0 -1.6C-2.2 -4.8 -2.4 -9.6 -0.2 -12.8C2 -9.8 1.8 -4.8 0 -1.6Z";
  out.push(spinOf(P, [13, 0, Z], rot(2, blade, 'class="sb-blade"'), ""));
  out.push(S(G.disc(5, 7.2, 2.2, FX, P), { tone: "hi", lit: true }));
  return { P, body: out.join("") };
}

